"""Sync the CLI's packaged configuration defaults from a LocalCloud image.

The LocalCloud image ships its configuration defaults, the document every `localcloud.yaml` overlays,
at /opt/localcloud/localcloud.defaults.yaml. The CLI packages the same document as
src/localcloud_cli/defaults/localcloud.v1.yaml, plus localcloud.v1.json (the same data, parsed
faster), to read the service catalog and host defaults without starting a container.

This script copies the image's document into the CLI:

    uv run python scripts/sync-gateway-defaults.py --image agentcloud/localcloud:0.1.10
    uv run python scripts/sync-gateway-defaults.py --image agentcloud/localcloud:0.1.10 --check
    uv run python scripts/sync-gateway-defaults.py --from path/to/localcloud.defaults.yaml

`--image` reads the file from a stopped container (`docker create` and `docker cp`; nothing runs
and no port is published), pulling the image if it is not local. `--from` reads a file instead.
`--check` exits 1 when the packaged files differ from what the source would produce.

The data is copied unchanged. The CLI has no settings of its own in this document: it mounts the
user's localcloud.yaml into the container as is, and the gateway refuses keys it does not know,
so a CLI-only key here would only mislead users who copy it. Comments are copied too, except that
the header is replaced and REWRITES drop implementation detail that does not belong in a public
package. A comment that still looks like source code (INTERNAL_PATTERNS) fails the sync, so a new
one is reviewed before it is published.

The result must be a valid overlay base: the CLI's strict YAML reader and its closed-set checks
accept it as a localcloud.yaml, and it defines every value the CLI reads from it (REQUIRED).
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import re
import subprocess
import sys
import tarfile
import tempfile
import textwrap
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
DEFAULTS = ROOT / "src" / "localcloud_cli" / "defaults"
YAML_PATH = DEFAULTS / "localcloud.v1.yaml"
JSON_PATH = DEFAULTS / "localcloud.v1.json"
IMAGE_PATH = "/opt/localcloud/localcloud.defaults.yaml"
SCHEMA_LABEL = "com.localcloud.config-schema"
SCHEMA_VERSION = 1

HEADER = """\
# LocalCloud configuration defaults (version 1)
# Generated by scripts/sync-gateway-defaults.py from the LocalCloud image's
# {image_path}. Do not edit by hand: re-run the script.
# Source: {source}
# Source sha256: {digest}
#
# localcloud.yaml is a recursive overlay on this document: omitted values inherit,
# and a mapping member set to null is deleted.
"""
SOURCE_LINE = re.compile(r"^# Source: (?P<source>.+)$", re.MULTILINE)
DIGEST_LINE = re.compile(r"^# Source sha256: (?P<digest>[0-9a-f]{64})$", re.MULTILINE)

# Rewrites applied to each comment paragraph (consecutive comment lines at one indentation),
# which is re-wrapped when one applies. Each drops implementation detail, keeping what a user
# needs to set the value.
REWRITES: tuple[tuple[re.Pattern[str], str], ...] = (
    # Database migration guard names.
    (re.compile(r"\s*\((?:[^()]*\b)?V\d+ guard[^()]*\)"), ""),
    # Source identifiers of the gateway's port constants.
    (re.compile(r"\s*\(config\.\w+(?:,? (?:and )?\w+)*\)"), ""),
    # Internal design document names.
    (re.compile(r"\s*\(see service-runtime-config\)"), ""),
    # Image build arguments.
    (re.compile(r"\s*The emulator build is selected at build time via \w+ in Dockerfile\."), ""),
)
# Words a public comment may use that look like source identifiers.
ALLOWED_CAMEL_CASE = {
    "AlloyDB",
    "BigQuery",
    "GraphQL",
    "LocalCloud",
    "MySQL",
    "PostgreSQL",
    "PubSub",
}
INTERNAL_PATTERNS: tuple[tuple[str, re.Pattern[str]], ...] = (
    ("source file", re.compile(r"\b[\w./-]+\.(?:go|java|kt|py|ts|tsx|sh)\b")),
    ("source path", re.compile(r"(?:^|[\s(])(?:pkg|cmd|internal|src)/\w")),
    ("Go identifier", re.compile(r"\b[a-z]+\.[A-Z]\w+")),
    ("migration version", re.compile(r"\bV\d+\b")),
    ("build file", re.compile(r"\bDockerfile\b")),
    ("work marker", re.compile(r"\b(?:TODO|FIXME|XXX)\b")),
)
CAMEL_CASE = re.compile(r"\b[A-Z][a-z0-9]+(?:[A-Z][a-z0-9]*)+\b")
COMMENT = re.compile(r"^(?P<indent>\s*)# ?(?P<text>.*)$")
# A comment after a value, on a line with no quoted string before it.
INLINE_COMMENT = re.compile(r"^[^#\"']*\S\s+# ?(?P<text>.*)$")


class SyncError(Exception):
    pass


# Source -------------------------------------------------------------------------------------------


def _docker(*args: str, binary: bool = False) -> Any:
    result = subprocess.run(["docker", *args], capture_output=True, check=False)
    if result.returncode != 0:
        raise SyncError(f"docker {args[0]} failed: {result.stderr.decode(errors='replace').strip()}")
    return result.stdout if binary else result.stdout.decode().strip()


def read_image(image: str) -> bytes:
    """The defaults file of an image, read from a container that is created but never started."""
    container = _docker("create", "--network", "none", image)
    try:
        label = _docker("image", "inspect", "--format", f'{{{{index .Config.Labels "{SCHEMA_LABEL}"}}}}', image)
        if label and label != str(SCHEMA_VERSION):
            raise SyncError(f"{image} has {SCHEMA_LABEL}={label}; the CLI reads version {SCHEMA_VERSION}")
        archive = _docker("cp", f"{container}:{IMAGE_PATH}", "-", binary=True)
    finally:
        subprocess.run(["docker", "rm", "-f", container], capture_output=True, check=False)
    with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
        member = tar.next()
        if member is None or not member.isfile():
            raise SyncError(f"{image} has no regular file at {IMAGE_PATH}")
        extracted = tar.extractfile(member)
        assert extracted is not None
        return extracted.read()


# Rendering ----------------------------------------------------------------------------------------


def _body(text: str) -> str:
    """The document without its leading comment block (the source's header, or ours)."""
    lines = text.splitlines()
    start = 0
    while start < len(lines) and (not lines[start].strip() or lines[start].lstrip().startswith("#")):
        start += 1
    return "\n".join(lines[start:]) + "\n"


def _paragraphs(lines: list[str]) -> list[tuple[str | None, list[str]]]:
    """Lines grouped as (indent, comment texts) paragraphs and (None, [line]) for the rest."""
    groups: list[tuple[str | None, list[str]]] = []
    for line in lines:
        match = COMMENT.match(line)
        if match is None:
            groups.append((None, [line]))
            continue
        indent = match.group("indent")
        if groups and groups[-1][0] == indent:
            groups[-1][1].append(match.group("text"))
        else:
            groups.append((indent, [match.group("text")]))
    return groups


def scrub_comments(body: str) -> str:
    output: list[str] = []
    for indent, texts in _paragraphs(body.splitlines()):
        if indent is None:
            output.extend(texts)
            continue
        joined = " ".join(texts)
        rewritten = joined
        for pattern, replacement in REWRITES:
            rewritten = pattern.sub(replacement, rewritten)
        if rewritten == joined:
            output.extend(f"{indent}# {text}".rstrip() for text in texts)
            continue
        width = max(len(indent) + 2 + len(text) for text in texts)
        output.extend(
            textwrap.wrap(rewritten, width=width, initial_indent=f"{indent}# ", subsequent_indent=f"{indent}# ")
        )
    return "\n".join(output) + "\n"


def internal_comments(text: str) -> list[str]:
    """Comment lines after the header that still look like implementation detail."""
    findings = []
    lines = text.splitlines()
    first = len(lines) - len(_body(text).splitlines())
    for number, line in enumerate(lines[first:], first + 1):
        match = COMMENT.match(line) or INLINE_COMMENT.match(line)
        if match is None:
            continue
        comment = match.group("text")
        for name, pattern in INTERNAL_PATTERNS:
            if pattern.search(comment):
                findings.append(f"line {number} ({name}): {comment}")
        for word in CAMEL_CASE.findall(comment):
            if word not in ALLOWED_CAMEL_CASE:
                findings.append(f"line {number} (identifier {word}): {comment}")
    return findings


def render(source_text: str, source: str, digest: str) -> tuple[str, str]:
    """The packaged YAML and JSON for a defaults document."""
    header = HEADER.format(image_path=IMAGE_PATH, source=source, digest=digest)
    text = header + "\n" + scrub_comments(_body(source_text))
    data = yaml.safe_load(text)
    return text, json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def provenance(packaged_yaml: str) -> tuple[str, str]:
    """The source and source digest a packaged YAML names in its header."""
    source = SOURCE_LINE.search(packaged_yaml)
    digest = DIGEST_LINE.search(packaged_yaml)
    if source is None or digest is None:
        raise SyncError(f"{YAML_PATH.name} has no sync header; run scripts/sync-gateway-defaults.py")
    return source.group("source"), digest.group("digest")


# Validation ---------------------------------------------------------------------------------------


def _get(document: Any, path: str) -> Any:
    value = document
    for key in path.split("."):
        if not isinstance(value, dict) or key not in value:
            raise SyncError(f"the defaults do not define {path}, which the CLI reads")
        value = value[key]
    return value


def validate(text: str) -> list[str]:
    """Why the YAML is not a valid overlay base for the CLI (empty when it is)."""
    sys.path.insert(0, str(ROOT / "src"))
    from localcloud_cli import config
    from localcloud_cli.errors import HostError

    problems: list[str] = []
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / "localcloud.yaml"
        path.write_text(text, encoding="utf-8")
        try:
            raw = config._read_config(path)
            config._validate_config_document(raw, skip_validation=False, diagnostics=[])
        except HostError as error:
            return [f"the CLI does not accept it as a localcloud.yaml: {error}"]
    document = yaml.safe_load(text)
    if raw != document:
        problems.append("the CLI's strict YAML reader and PyYAML read different values")
    if document.get("version") != SCHEMA_VERSION:
        problems.append(f"version is {document.get('version')!r}, not {SCHEMA_VERSION}")
    try:
        if _get(document, "host.docker_socket") not in {"auto", True, False}:
            problems.append("host.docker_socket is not auto, true or false")
        if _get(document, "server.gateway.port") != 5380:
            problems.append("server.gateway.port is not 5380")
        catalog = _get(document, "services.catalog")
        if not isinstance(catalog, dict) or not catalog:
            problems.append("services.catalog is not a non-empty mapping")
            catalog = {}
        for service_id, definition in catalog.items():
            if not isinstance(definition, dict):
                problems.append(f"services.catalog.{service_id} is not a mapping")
                continue
            if type(definition.get("defaultEnabled")) is not bool:
                problems.append(f"services.catalog.{service_id}.defaultEnabled is not a boolean")
            if not isinstance(definition.get("displayName"), str):
                problems.append(f"services.catalog.{service_id}.displayName is not a string")
            dependencies = definition.get("runtimeDependencies", [])
            if not isinstance(dependencies, list):
                problems.append(f"services.catalog.{service_id}.runtimeDependencies is not a list")
        if "cloudsql" in catalog and not isinstance(
            _get(document, "services.catalog.cloudsql.additionalPorts.mysql"), int
        ):
            problems.append("services.catalog.cloudsql.additionalPorts.mysql is not a port")
    except SyncError as error:
        problems.append(str(error))
    problems.extend(f"internal comment, add a REWRITES entry: {line}" for line in internal_comments(text))
    return problems


# Command ------------------------------------------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--image", help="LocalCloud image to read the defaults from, e.g. agentcloud/localcloud:0.1.10")
    source.add_argument("--from", dest="path", type=Path, help="defaults file to read instead of an image")
    parser.add_argument("--check", action="store_true", help="verify the packaged files instead of writing them")
    args = parser.parse_args(argv)
    try:
        if args.image:
            raw = read_image(args.image)
            label = args.image
        else:
            raw = args.path.read_bytes()
            label = f"{args.path.name} (a local file, not a published image)"
        text, data = render(raw.decode("utf-8"), label, hashlib.sha256(raw).hexdigest())
        problems = validate(text)
    except (OSError, UnicodeError, yaml.YAMLError, SyncError) as error:
        print(f"sync-gateway-defaults: {error}", file=sys.stderr)
        return 2
    if problems:
        print("sync-gateway-defaults: the result is not a valid overlay base:", file=sys.stderr)
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        return 2
    if args.check:
        stale = [
            path.relative_to(ROOT)
            for path, expected in ((YAML_PATH, text), (JSON_PATH, data))
            if not path.is_file() or path.read_text(encoding="utf-8") != expected
        ]
        if stale:
            print(f"{', '.join(map(str, stale))} differ from {label}; re-run without --check", file=sys.stderr)
            return 1
        print(f"packaged defaults match {label}")
        return 0
    YAML_PATH.write_text(text, encoding="utf-8")
    JSON_PATH.write_text(data, encoding="utf-8")
    print(f"wrote {YAML_PATH.relative_to(ROOT)} and {JSON_PATH.relative_to(ROOT)} from {label}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
